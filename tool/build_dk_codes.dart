// #4417 -- writes lib/core/data/dk_code.dart: every `DK…` refusal code the migrations raise
// (`using errcode = 'DK…'` or `public.refuse('DK…', …)`), one constant each, so the app spells a
// code once and a typing error is a compile error. The same scan `dk_codes_test` reads: SQL
// and Dart cannot differ (the test fails when a code exists in one and not the other).
//
//   dart run tool/build_dk_codes.dart            # write the file
//   dart run tool/build_dk_codes.dart --check    # exit 1 when it is not what the migrations say
import 'dart:io';

final _raised = RegExp(
  r"errcode\s*=\s*'(DK[A-Z0-9]{3})'|\brefuse\(\s*'(DK[A-Z0-9]{3})'",
);

/// The DK codes the migrations under [dir] raise, sorted.
List<String> raisedCodes(String dir) {
  final out = <String>{};
  for (final f in Directory(dir).listSync().whereType<File>()) {
    if (!f.path.endsWith('.sql')) continue;
    for (final m in _raised.allMatches(f.readAsStringSync())) {
      out.add((m.group(1) ?? m.group(2))!);
    }
  }
  return out.toList()..sort();
}

/// The text of the generated file for [codes].
String dkCodeSource(List<String> codes) {
  final b = StringBuffer()
    ..writeln('// SPDX-License-Identifier: AGPL-3.0-or-later')
    ..writeln('//')
    ..writeln('// GENERATED by `dart run tool/build_dk_codes.dart` -- do not edit (#4417).')
    ..writeln('// Every DK refusal code a migration raises. The app reads codes by these constants.')
    ..writeln()
    ..writeln('/// The DK refusal codes of the server, one constant each.')
    ..writeln('abstract final class DkCode {');
  for (final c in codes) {
    b.writeln("  static const ${c.toLowerCase()} = '$c';");
  }
  b.writeln('}');
  return b.toString();
}

void main(List<String> args) {
  final text = dkCodeSource(raisedCodes('supabase/migrations'));
  final file = File('lib/core/data/dk_code.dart');
  if (args.contains('--check')) {
    final same = file.existsSync() && file.readAsStringSync() == text;
    if (!same) {
      stderr.writeln('lib/core/data/dk_code.dart is not what the migrations raise: run dart run tool/build_dk_codes.dart');
    }
    exit(same ? 0 : 1);
  }
  file.writeAsStringSync(text);
  stdout.writeln('wrote ${file.path}');
}
