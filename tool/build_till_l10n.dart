// The terminal consumes a bounded subset of the application's canonical ARB.
// Unsupported ICU messages fail instead of leaking untranslated placeholders.
import 'dart:convert';
import 'dart:io';

const List<String> tillLocales = ['en', 'fr', 'de', 'es', 'it'];

String buildTillHeader(Directory fragments, List<String> keys) {
  if (keys.isEmpty ||
      keys.toSet().length != keys.length ||
      keys.any((key) => !RegExp(r'^[a-zA-Z][a-zA-Z0-9]*$').hasMatch(key))) {
    throw const FormatException('Terminal keys must be unique identifiers.');
  }
  final names = [...keys]..sort();
  final messages = <String, Map<String, String>>{};
  final files = fragments.listSync().whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final locale in tillLocales) {
    final values = <String, String>{};
    for (final file in files.where((f) => f.path.endsWith('_$locale.arb'))) {
      final decoded = jsonDecode(file.readAsStringSync());
      if (decoded is! Map<String, dynamic>) {
        throw FormatException('Invalid ARB object: ${file.path}');
      }
      for (final key in names) {
        if (!decoded.containsKey(key)) continue;
        if (values.containsKey(key)) {
          throw FormatException('Duplicate terminal key: $locale/$key');
        }
        final value = decoded[key];
        if (value is! String ||
            value.isEmpty ||
            value.contains(RegExp(r'[{}\x00-\x1f\x7f]')) ||
            utf8.decode(utf8.encode(value)) != value) {
          throw FormatException('Unsupported terminal message: $locale/$key');
        }
        if (utf8.encode(value).length > 256) {
          throw FormatException(
            'Terminal message exceeds 256 UTF-8 bytes: $key',
          );
        }
        values[key] = value;
      }
    }
    for (final key in names) {
      if (!values.containsKey(key)) {
        throw FormatException('Missing terminal translation: $locale/$key');
      }
    }
    messages[locale] = values;
  }
  final out = StringBuffer('''// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by tool/build_till_l10n.dart; edit canonical ARB fragments.
#pragma once
#include <cstddef>
#include <cstdint>
#include <cstring>

namespace deskilo::till {
enum class Locale : std::uint8_t { en, fr, de, es, it };
struct Message { const char* key; const char* values[5]; };
inline constexpr Message messages[] = {
''');
  for (final key in names) {
    out.writeln(
      '  {${jsonEncode(key)}, {${[for (final locale in tillLocales) jsonEncode(messages[locale]![key])].join(', ')}}},',
    );
  }
  out.write('''};
inline const char* text(Locale locale, const char* key) {
  const auto index = static_cast<std::size_t>(locale);
  if (key == nullptr || index >= 5) return nullptr;
  for (const auto& message : messages) {
    if (std::strcmp(message.key, key) == 0) return message.values[index];
  }
  return nullptr;
}
}  // namespace deskilo::till
''');
  return out.toString();
}

void main(List<String> args) {
  String option(String name, String fallback) {
    final index = args.indexOf(name);
    if (index < 0) return fallback;
    if (index + 1 >= args.length) throw FormatException('Missing $name value');
    return args[index + 1];
  }

  try {
    final fragments = Directory(option('--fragments', 'lib/l10n/_fragments'));
    final keyFile = File(option('--keys', 'firmware/till/l10n_keys.json'));
    final rawKeys = jsonDecode(keyFile.readAsStringSync());
    if (rawKeys is! List<Object?> || rawKeys.any((key) => key is! String)) {
      throw const FormatException(
        'Terminal key manifest must be a string list.',
      );
    }
    final rendered = buildTillHeader(fragments, rawKeys.cast<String>());
    final output = File(
      option('--out', 'firmware/till/generated/till_strings.h'),
    );
    if (args.contains('--check')) {
      if (!output.existsSync() || output.readAsStringSync() != rendered) {
        stderr.writeln(
          'Terminal translations differ; run tool/build_till_l10n.dart.',
        );
        exitCode = 1;
      }
      return;
    }
    output.parent.createSync(recursive: true);
    output.writeAsStringSync(rendered);
    stdout.writeln('Wrote ${output.path}');
  } on FormatException catch (error, stack) {
    stderr.writeln('$error\n$stack');
    exitCode = 1;
  } on FileSystemException catch (error, stack) {
    stderr.writeln('$error\n$stack');
    exitCode = 1;
  }
}
