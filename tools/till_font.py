"""#4456 -- the till's accented glyphs as LVGL 8 fonts, written without lv_font_conv.

LVGL's built-in Montserrat fonts carry ASCII and the symbols only, so a German, French, Spanish or Italian text would lose
its accents on the board. This renders the Latin-1 supplement, Latin Extended-A, the dashes and the euro sign of the same
Montserrat Medium (SIL OFL 1.1, fonts/OFL.txt) at the sizes the screens use, 4 bits per pixel, and writes one C font per
size whose fallback is the built-in font of that size: ASCII and the symbols still come from LVGL.

    python3 tools/till_font.py            # writes firmware/till/main/till_font_<size>.c
Needs Pillow (FreeType); the output is committed, the board build does not run this.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "firmware", "till", "fonts", "Montserrat-Medium.ttf")
OUT = os.path.join(ROOT, "firmware", "till", "main")
SIZES = (14, 16, 20, 28)
CODEPOINTS = list(range(0xA0, 0x180)) + [0x2013, 0x2014, 0x20AC]


def glyph(font, cp):
    ch = chr(cp)
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    w, h = max(0, right - left), max(0, bottom - top)
    adv = round(font.getlength(ch) * 16)
    pixels = []
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        pixels = [v >> 4 for v in img.getdata()]
    return {"w": w, "h": h, "ofs_x": left, "ofs_y": -bottom, "adv": adv, "px": pixels}


def pack(pixels):
    """A continuous 4 bpp stream, high nibble first: the uncompressed layout of lv_font_fmt_txt."""
    out = bytearray()
    for i in range(0, len(pixels), 2):
        hi = pixels[i]
        lo = pixels[i + 1] if i + 1 < len(pixels) else 0
        out.append((hi << 4) | lo)
    return out


def write(size):
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    glyphs = [glyph(font, cp) for cp in CODEPOINTS]
    name = f"till_font_{size}"
    bitmap = bytearray()
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0: none */"]
    for cp, g in zip(CODEPOINTS, glyphs):
        if not (-128 <= g["ofs_x"] < 128 and -128 <= g["ofs_y"] < 128 and g["w"] < 256 and g["h"] < 256 and g["adv"] < 4096):
            sys.exit(f"U+{cp:04X} at {size}px does not fit the glyph descriptor")
        dsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {g['adv']}, .box_w = {g['w']}, .box_h = {g['h']}, "
                   f".ofs_x = {g['ofs_x']}, .ofs_y = {g['ofs_y']}}} /* U+{cp:04X} */")
        bitmap += pack(g["px"])
    if len(bitmap) >= 1 << 20:
        sys.exit("the bitmap is beyond the descriptor's 20-bit index")
    start = CODEPOINTS[0]
    offsets = ", ".join(str(cp - start) for cp in CODEPOINTS)
    rows = [", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]
    src = f"""// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by tools/till_font.py -- do not edit. Montserrat Medium {size}px (SIL OFL 1.1, fonts/OFL.txt), 4 bpp:
// U+00A0-U+017F, the dashes and the euro sign. ASCII and the symbols come from the fallback, lv_font_montserrat_{size}.
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {(','+chr(10)+'    ').join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(','+chr(10)).join(dsc)}
}};

static const uint16_t unicode_list[] = {{{offsets}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {start}, .range_length = {CODEPOINTS[-1] - start + 1}, .glyph_id_start = 1, .unicode_list = unicode_list,
     .glyph_id_ofs_list = NULL, .list_length = {len(CODEPOINTS)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &cache,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = &lv_font_montserrat_{size},
    .user_data = NULL,
}};
"""
    with open(os.path.join(OUT, f"{name}.c"), "w") as f:
        f.write(src)
    return len(bitmap)


if __name__ == "__main__":
    for s in SIZES:
        print(f"till_font_{s}.c: {write(s)} bytes of glyphs")
