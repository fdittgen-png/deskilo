"""#4456 -- the till's screen texts in five languages, as one C table.

firmware/till/l10n/till_<lang>.json hold the same keys (English first); this checks that every language has every key and the
same printf conversions in the same order, then writes firmware/till/main/strings.{h,c}. The board picks its language from
the `lang` setting (tools/till_provision.py --lang), English when unset or unknown.

    python3 tools/build_till_strings.py           # write
    python3 tools/build_till_strings.py --check   # exit 1 if the committed files are not what this writes
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L10N = os.path.join(ROOT, "firmware", "till", "l10n")
MAIN = os.path.join(ROOT, "firmware", "till", "main")
LANGS = ("en", "de", "fr", "es", "it")
SPEC = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l)?[diuxXsc%]")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def build():
    tables = {l: json.load(open(os.path.join(L10N, f"till_{l}.json"), encoding="utf-8")) for l in LANGS}
    keys = list(tables["en"])
    problems = []
    for l in LANGS[1:]:
        if list(tables[l]) != keys:
            problems.append(f"{l}: keys differ from English ({sorted(set(keys) ^ set(tables[l]))})")
            continue
        for k in keys:
            if SPEC.findall(tables[l][k]) != SPEC.findall(tables["en"][k]):
                problems.append(f"{l}.{k}: conversions {SPEC.findall(tables[l][k])} differ from English {SPEC.findall(tables['en'][k])}")
    if problems:
        sys.exit("\n".join(problems))
    h = ["// SPDX-License-Identifier: AGPL-3.0-or-later",
         "// GENERATED by tools/build_till_strings.py from firmware/till/l10n -- do not edit.",
         "#pragma once", "", "typedef enum {"]
    h += [f"    S_{k.upper()}," for k in keys] + ["    S__COUNT", "} str_id_t;", "",
          "// Sets the language by its code (en, de, fr, es, it); anything else is English.",
          "void strings_set_lang(const char *code);",
          "// The text of [id] in the language set.",
          "const char *T(str_id_t id);", ""]
    c = ["// SPDX-License-Identifier: AGPL-3.0-or-later",
         "// GENERATED by tools/build_till_strings.py from firmware/till/l10n -- do not edit.",
         '#include "strings.h"', "#include <string.h>", "",
         f"static const char *const TEXTS[{len(LANGS)}][S__COUNT] = {{"]
    for l in LANGS:
        c.append(f"    {{ /* {l} */")
        c += [f"        {c_str(tables[l][k])}," for k in keys]
        c.append("    },")
    c += ["};", "", "static int s_lang;", "",
          "void strings_set_lang(const char *code) {",
          f"    static const char *const codes[{len(LANGS)}] = {{{', '.join(c_str(l) for l in LANGS)}}};",
          "    s_lang = 0;",
          f"    for (int i = 0; code && i < {len(LANGS)}; i++) if (!strcmp(code, codes[i])) s_lang = i;",
          "}", "",
          "const char *T(str_id_t id) { return id < S__COUNT ? TEXTS[s_lang][id] : \"\"; }", ""]
    return "\n".join(h), "\n".join(c)


if __name__ == "__main__":
    h, c = build()
    paths = {os.path.join(MAIN, "strings.h"): h, os.path.join(MAIN, "strings.c"): c}
    if "--check" in sys.argv:
        stale = [p for p, t in paths.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if stale:
            sys.exit("stale: " + ", ".join(stale) + " -- run python3 tools/build_till_strings.py")
        print("strings up to date")
    else:
        for p, t in paths.items():
            open(p, "w", encoding="utf-8").write(t)
        print(f"wrote {len(paths)} files")
