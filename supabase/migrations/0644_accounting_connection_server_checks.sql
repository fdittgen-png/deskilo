-- (two nullable columns and their check on accounting_connections; one
-- registry function and one service writer added; accounting_connection_json
-- and open_accounting_connection_v1 restated whole)
--
-- 0644 (#2370) -- two server checks of the accounting connections.
--
-- What the target answered to a revocation. accounting-connect revokes a
-- connection here first, with the caller's own token, and then asks the
-- target (RFC 7009) to forget the token, best effort. Until now that answer
-- lived only in the one response: the connection's card could not say that
-- the target never confirmed, and that the person should remove DesKilo in
-- the target's own settings. The outcome is known only AFTER the local
-- revocation, and a value the caller could pass to its own revoke would be
-- one the caller could forge, so it is recorded by the edge function alone
-- (service role) through record_accounting_revocation, on the revoked row:
-- `remote_revocation` (revoked / failed / not_supported) and when.
-- revoke_accounting_connection_v1 is unchanged. A connection revoked before
-- this file has no outcome and the card says nothing of one.
--
-- Which targets a connection is opened for. open_accounting_connection_v1
-- took any id of the right shape: a connection to a target the app does
-- not define, or by a way the target does not take, was stored and then
-- refused by every door after it. The list is the app's target registry
-- (accounting_format.dart `accountingTargets`, `connectsBy`), GENERATED by
-- tool/build_accounting_targets_sql.dart into accounting_connection_targets();
-- accounting_targets_sql_test pins the latest definition to the Dart
-- descriptor. An unknown target or a way it is not connected by is refused
-- with 22023.
--
-- accounting_connection_json and open_accounting_connection_v1 are restated
-- whole: 0595 defines both and no later migration patches either (0628
-- restates set_accounting_token_v1 only).

alter table public.accounting_connections
  add column remote_revocation text
    check (remote_revocation in ('revoked', 'failed', 'not_supported')),
  add column remote_revocation_at timestamptz,
  -- An outcome belongs to a revoked connection, and has its instant.
  add constraint accounting_connections_remote_revocation_revoked
    check ((remote_revocation is null) = (remote_revocation_at is null)
           and (remote_revocation is null or revoked_at is not null));

