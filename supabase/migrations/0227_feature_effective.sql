grant execute on function public.feature_raw(jsonb, text) to authenticated;

create or replace function public.feature_effective_in(p_flags jsonb, p_key text)
returns boolean
language plpgsql
immutable
set search_path = public
as $$
declare
  v_registry jsonb := public.feature_registry();
  v_key text := p_key;
  v_depth int := 0;
begin
  -- An unknown key is off: a gate must never open on a typo.
  if not v_registry ? p_key then
    return false;
  end if;
  while v_key is not null loop
    if not public.feature_raw(p_flags, v_key) then
      return false;
    end if;
    v_key := v_registry -> v_key ->> 'parent';
    v_depth := v_depth + 1;
    if v_depth > 32 then
      raise exception 'feature registry cycle at %', p_key;
    end if;
  end loop;
  return true;
end;
$$;

