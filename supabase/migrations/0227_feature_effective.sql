-- 0227 (#1333, #1332) — the server decides whether a feature is on the way
-- the app does.
--
-- The client: a stored JSON boolean over the registry default, then every
-- `requires` parent on (`resolveEnabledFeatures` → `effectiveFeatures`). A
-- child stays stored `true` under a parent switched off — that is the
-- design (#800), so switching the parent back on restores it.
--
-- The server read the one flag in front of each gate, each with its own
-- default. Proven rolled back on the dev project before this file:
-- `{"moneyTab": false, "scheduledExpenses": true}` let
-- `create_expense_schedule` past its gate while the app showed the feature
-- off. The same held for price negotiations, invoice settlement, accessory
-- supplements and the admin invoicing grant in `has_permission_raw`.
--
-- ## One source, generated
--
-- `feature_registry()` is the Dart `featureManifest` — parent, default,
-- core — generated by `dart run tool/build_feature_registry_sql.dart` and
-- pinned by `test/lint/feature_registry_sql_test.dart`, which requires the
-- latest definition here to match the manifest byte for byte. Nobody types
-- a parent map twice.
--
-- * `feature_raw(flags, key)`        — a JSON boolean, or the default.
--                                     `"yes"`, `1`, `"true"` are not booleans.
-- * `feature_effective_in(flags, key)` — raw AND every parent raw.
-- * `feature_effective(ws, key)`     — the same, for a workspace row.
-- * `resolved_feature_flags(flags)`  — every registry key written out.
--
-- ## Every gate asks the helper
--
-- Twenty functions read `feature_flags`; every gate among them now calls
-- `feature_effective`. Each patch asserts its anchor — a silent no-op
-- here would leave a gate the old way while the lint said otherwise.
--
-- ## The import validates and completes the map
--
-- `import_workspace_configuration` replaced the map with whatever the file
-- held: no key pattern, no boolean check, and a partial map let 45
-- default-on platform features resolve ON in a workspace created with them
-- off (#1063). It now refuses what `set_feature_flags` refuses and writes
-- absent keys as a new workspace would (core → its default, platform →
-- off). The export writes every key resolved, so a dev → prod deployment
-- carries exactly the effective choice of the source and the completion
-- only ever applies to a hand-made or older file.
--
-- A stored child `true` under an off parent is NOT rewritten anywhere:
-- validity is a property of the effective set, never of the raw map (#800).

