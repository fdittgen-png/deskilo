-- What an imported map becomes: the checks set_feature_flags makes, then
-- every registry key the file does not carry written as a NEW workspace
-- would have it — core at its default, platform off.
create or replace function public.imported_feature_flags(p_flags jsonb)
returns jsonb
language plpgsql
immutable
set search_path = public
as $$
declare
  v_registry jsonb := public.feature_registry();
  v_out jsonb := '{}'::jsonb;
  v_key text;
  v_value jsonb;
begin
  if p_flags is null or jsonb_typeof(p_flags) <> 'object' then
    raise exception 'feature flags must be an object';
  end if;
  for v_key, v_value in select * from jsonb_each(p_flags) loop
    if v_key !~ '^[A-Za-z][A-Za-z0-9]{0,63}$' then
      raise exception 'invalid feature key %', v_key;
    end if;
    if jsonb_typeof(v_value) <> 'boolean' then
      raise exception 'feature % must be true or false', v_key;
    end if;
    v_out := v_out || jsonb_build_object(v_key, v_value);
  end loop;
  for v_key in select jsonb_object_keys(v_registry) loop
    if not v_out ? v_key then
      v_out := v_out || jsonb_build_object(v_key,
        coalesce((v_registry -> v_key ->> 'core')::boolean, false)
          and coalesce((v_registry -> v_key ->> 'default')::boolean, false));
    end if;
  end loop;
  return v_out;
end;
$$;

