create or replace function public.resolved_feature_flags(p_flags jsonb)
returns jsonb
language sql
immutable
set search_path = public
as $$
  select coalesce(jsonb_object_agg(k, public.feature_raw(p_flags, k)), '{}'::jsonb)
         || coalesce((select jsonb_object_agg(e.key, e.value)
                        from jsonb_each(coalesce(p_flags, '{}'::jsonb)) e
                       where not public.feature_registry() ? e.key
                         and jsonb_typeof(e.value) = 'boolean'), '{}'::jsonb)
    from jsonb_object_keys(public.feature_registry()) k;
$$;

